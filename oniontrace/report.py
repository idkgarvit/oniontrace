"""Run report: what the pipeline found, and what it did not.

The report is generated rather than written by hand for the same reason the deck is:
a document that restates numbers by copy-paste drifts away from the code that produced
them, and the drift is invisible until someone checks.

Every section names the limit of its own numbers. A stage that did not run appears as
a stated gap rather than being omitted, because an absent section reads as "nothing to
report" when it actually means "we do not know".
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from oniontrace.pipeline import PipelineResult


def _fmt(value: Any) -> str:
    if isinstance(value, float):
        return f"{value:.3f}"
    return str(value)


def write_report(result: PipelineResult, path: Path) -> Path:
    """Render the run to Markdown and return where it landed."""

    lines: list[str] = []
    a = lines.append

    a(f"# ONIONTRACE pipeline run `{result.run_id}`")
    a("")
    a(f"- **Case:** `{result.case_id}`")
    a(f"- **Seed:** `{result.seed}`")
    a(f"- **Started:** {result.started_at}")
    a(f"- **Finished:** {result.finished_at}")
    a(f"- **Outcome:** {'all stages completed' if result.ok else 'one or more stages failed'}")
    a("")
    a("> Every figure below is generated by the stage that produced it. Claim boundaries")
    a("> are stated next to the number they bound, not collected in a footnote.")
    a("")

    # -- stage table ---------------------------------------------------- #
    a("## Stages")
    a("")
    a("| Stage | Result | Duration | Note |")
    a("|---|---|---|---|")
    for s in result.stages:
        if s.skipped_because:
            state, note = "skipped", s.skipped_because
        elif s.ok:
            state, note = "ok", ""
        else:
            state, note = "**failed**", (s.error or "")
        a(f"| `{s.name}` | {state} | {s.duration_ms} ms | {note} |")
    a("")

    # -- per stage detail ----------------------------------------------- #
    farm = result.stage("farm")
    if farm and farm.ok:
        s = farm.summary
        a("## Ground truth (farm)")
        a("")
        a(f"{s['services']} services in {s['clusters']} clusters, {s['personas']} personas, "
          f"{s['flaws']} planted flaws, {s['hard_negatives']} hard negatives. "
          f"Fingerprint `{s['fingerprint']}`.")
        a("")
        a("**Limit.** These are our own services and our own ground truth. Every metric "
          "below measures a detector against a fixture, not behaviour on the live network.")
        a("")

    det = result.stage("detect")
    if det:
        a("## M2 — misconfiguration detection")
        a("")
        if det.ok:
            s = det.summary
            a(f"{s['findings']} findings across {s['services_scanned']} services "
              f"({s['services_with_findings']} with at least one), from {s['rule_count']} rules.")
            a("")
            if s["by_kind"]:
                a("| Rule kind | Findings |")
                a("|---|---|")
                for kind, count in s["by_kind"].items():
                    a(f"| `{kind}` | {count} |")
                a("")
            from farm.catalogue import rules_without_hard_negative

            gap = rules_without_hard_negative()
            if gap:
                a(f"**Limit.** For {len(gap)} of the rule set no negative fixture exists "
                  f"({', '.join(gap)}), so a false positive could not have been observed even "
                  "if present.")
            else:
                a("**Coverage.** Every rule in this table has a negative fixture served for it: "
                  "a page that looks like the flaw and carries the feature that means it is not. "
                  "A false positive could have been observed on each one, so the zeros above are "
                  "measured rather than assumed.")
        else:
            a(f"**Did not run.** {det.error}")
        a("")

    corr = result.stage("correlate")
    if corr:
        a("## M2b — cross-service correlation")
        a("")
        if corr.ok:
            s = corr.summary
            a(f"Frequency cap {s['frequency_cap']}, {s['queries']} queries. "
              f"Precision@1 **{_fmt(s['precision_at_1'])}**, "
              f"precision@3 **{_fmt(s['precision_at_3'])}**.")
            a("")
            a("**Limit.** Precision is measured against cluster membership in a synthetic "
              "farm with fixed topology and a single seed family.")
        else:
            a(f"**Did not run.** {corr.error}")
        a("")

    att = result.stage("attribute")
    if att:
        a("## M5 — attribution, with the code-mix block")
        a("")
        if att.ok:
            s = att.summary
            a("| Model | hit@1 long | hit@1 short |")
            a("|---|---|---|")
            a(f"| function words + behaviour | {_fmt(s['combined_hit@1_long'])} "
              f"| {_fmt(s['combined_hit@1_short'])} |")
            a(f"| + code-mix when detected (gate {s['mix_gate']}) "
              f"| {_fmt(s['gated_hit@1_long'])} | {_fmt(s['gated_hit@1_short'])} |")
            a("")
            a(f"**Scope limit.** {s['scope_limit']}")
            a("")
            a("**Limit on the gain.** The code-mix improvement is measured on four "
              "mixed-regime personas, which is one query flipping. It is a direction, not "
              "a magnitude, and the gate value was fitted on the same farm.")
        else:
            a(f"**Did not run.** {att.error}")
        a("")

    gr = result.stage("graph")
    if gr:
        a("## M3 — identity graph")
        a("")
        if gr.ok:
            s = gr.summary
            a(f"{s['artefacts']} artefacts, {s['entities']} entities, "
              f"{s['edges']} proposed links, {s['conflicts']} conflicts.")
            a("")
            a("| Link status | Count |")
            a("|---|---|")
            for status, count in s["by_status"].items():
                a(f"| `{status}` | {count} |")
            a("")
            a("**Limit.** A proposed link is not an assertion. Nothing is merged without a "
              "named analyst, and vendor defaults are excluded from every link.")
            a("")
            a(f"Graph database: `{s['db']}`")
            a("")
            a("Open the console with:")
            a("")
            a("```bash")
            a(f"python -m dashboard    # then browse to /case/{result.case_id}")
            a("```")
        else:
            a(f"**Did not run.** {gr.error}")
        a("")

    # -- honest closing -------------------------------------------------- #
    a("## What this run does not establish")
    a("")
    a("- Nothing here was collected from a live third-party target. Acquisition runs "
      "against fixtures, and the live transport is deliberately dark.")
    a("- The correlation and attribution figures describe a synthetic farm built by the "
      "same team that wrote the detectors, so they are an upper bound.")
    a("- The pipeline records its own failures. A stage shown as skipped is not a stage "
      "that found nothing; it is a stage whose answer is unknown.")
    a("")

    path.write_text("\n".join(lines), encoding="utf-8")
    return path

#!/usr/bin/env python3
"""Run the paper's secondary experiments and write one readable record.

The headline harness answers one seed and one farm shape. This runs the paired
style-drift test, a 20-seed sweep, six farm topologies, a frequency-cap ablation and
a query-level significance test. It writes both the JSON the paper cites and a
Markdown digest a person can read.

    python3 scripts/run_experiments.py

Writes:
    out/experiments.json
    out/experiments.md

The VERDICT line is deliberately about the design and the invariants, not about the
drift direction: a result that contradicts the hypothesis is still a result, and a
runner that fails when the data disagree is a runner that invites the data to be
adjusted.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from eval.experiments import DEFAULT_SEED, run_all  # noqa: E402

JSON_PATH = ROOT / "out" / "experiments.json"
MD_PATH = ROOT / "out" / "experiments.md"


def _pct(value: float) -> str:
    return f"{value:.3f}"


def _markdown(document: dict) -> str:
    drift = document["paired_drift"]
    seeds = document["seed_sweep"]
    topology = document["topology_sweep"]
    cap = document["cap_ablation"]
    paired = document["correlation_paired_test"]

    lines = [
        "# Secondary experiments",
        "",
        f"Seed {DEFAULT_SEED}. Generated by `python3 scripts/run_experiments.py`.",
        "",
        "## Paired style drift",
        "",
        "One fixed profile per persona; the query window moves from before to after the "
        "recorded drift point. Template reusers have no drift and are a placebo.",
        "",
        "| model | pre hit@1 | post hit@1 | pre hit@3 | post hit@3 | Δ hit@3 [95% CI] | McNemar p | placebo hit@3 |",
        "|---|---:|---:|---:|---:|---|---:|---:|",
    ]
    for model, entry in drift["models"].items():
        drifted = entry["drifted"]
        stable = entry["stable_placebo"]
        lines.append(
            f"| {model} | {_pct(drifted['pre']['hit@1'])} | "
            f"{_pct(drifted['post']['hit@1'])} | {_pct(drifted['pre']['hit@3'])} | "
            f"{_pct(drifted['post']['hit@3'])} | "
            f"{drifted['delta_hit@3']['delta']:+.3f} "
            f"[{drifted['delta_hit@3']['ci95'][0]:+.3f}, "
            f"{drifted['delta_hit@3']['ci95'][1]:+.3f}] | "
            f"{drifted['mcnemar_hit@3']['p_exact']:.4f} | "
            f"{_pct(stable['pre']['hit@3'])} → {_pct(stable['post']['hit@3'])} |"
        )

    lines += [
        "",
        f"n = {drift['design']['drifted_personas']} drifting personas, "
        f"{drift['design']['stable_personas']} placebo personas, pool "
        f"{drift['design']['candidate_pool']}.",
        "",
        "## Seed sweep",
        "",
        f"{seeds['design']['n_clusters']}x{seeds['design']['services_per_cluster']}, "
        f"{len(seeds['design']['seeds'])} seeds. Seeds vary identifiers and corpora, "
        "not the planted collision graph.",
        "",
        "| metric | mean | sd | min | max |",
        "|---|---:|---:|---:|---:|",
    ]
    for key in (
        "naive_link_precision",
        "frozen_link_precision",
        "filtered_link_precision",
        "naive_false_merge",
        "filtered_false_merge",
        "heldout_filtered_link_precision",
        "naive_precision@1",
        "filtered_precision@1",
        "attribution_text_full_drift_hit@3",
        "attribution_text_function_drift_hit@3",
    ):
        summary = seeds["summary"][key]
        lines.append(
            f"| {key} | {summary['mean']:.4f} | {summary['sd']:.4f} | "
            f"{summary['min']:.4f} | {summary['max']:.4f} |"
        )
    lines += [
        "",
        "Invariants: "
        + ", ".join(
            f"{name}={value}" for name, value in seeds["invariants"].items()
        )
        + ".",
        "",
        "## Topology sweep",
        "",
        "Three seeds per shape. The frequency cap is `max(2, services_per_cluster)`, so "
        "this varies the derivation as well as the scale.",
        "",
        "| shape | cap | naive link P | frozen link P | filtered link P | filtered FM | held-out filtered P |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for shape, entry in topology["by_topology"].items():
        summary = entry["summary"]
        lines.append(
            f"| {shape} | {int(summary['frequency_cap']['mean'])} | "
            f"{summary['naive_link_precision']['mean']:.3f} | "
            f"{summary['frozen_link_precision']['mean']:.3f} | "
            f"{summary['filtered_link_precision']['mean']:.3f} | "
            f"{summary['filtered_false_merge']['mean']:.3f} | "
            f"{summary['heldout_filtered_link_precision']['mean']:.3f} |"
        )

    lines += [
        "",
        "## Frequency-cap ablation",
        "",
        "| cap | proposed | precision | recall | false merge | precision@1 |",
        "|---:|---:|---:|---:|---:|---:|",
    ]
    for row in cap["rows"]:
        label = "none" if row["cap"] is None else str(row["cap"])
        marker = " (derived)" if row["derived_cap"] else ""
        lines.append(
            f"| {label}{marker} | {row['proposed']} | {row['precision']:.3f} | "
            f"{row['recall']:.3f} | {row['false_merge_rate']:.3f} | "
            f"{row['precision@1']:.3f} |"
        )

    stats = paired["false_links"]
    lines += [
        "",
        "## Query-level significance",
        "",
        f"Top-1: naive {paired['top1']['naive_correct']}/"
        f"{paired['design']['queries']}, filtered {paired['top1']['filtered_correct']}/"
        f"{paired['design']['queries']}; McNemar exact p = "
        f"{paired['top1']['mcnemar_p_exact']:.3f}.",
        "",
        f"Non-mate candidates surfaced: naive "
        f"{stats['naive_nonmate_candidates_total']} directed "
        f"({stats['naive_unique_false_pairs']} distinct pairs), filtered "
        f"{stats['filtered_nonmate_candidates_total']} "
        f"({stats['filtered_unique_false_pairs']} distinct pairs). "
        f"Sign test on the 12 queries: p = {stats['sign_test_p_exact']:.5f}. "
        f"Mean change {stats['delta_mean_candidates_per_query']:+.2f} candidates per "
        f"query, 95% CI [{stats['delta_ci95'][0]:+.2f}, {stats['delta_ci95'][1]:+.2f}].",
        "",
        "The top-1 difference is not significant at n=12; the link-proposal difference "
        "is. That is the honest split, and it is the same lesson as the headline: the "
        "ranking view is weaker than the link view.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    document = run_all()
    JSON_PATH.parent.mkdir(parents=True, exist_ok=True)
    JSON_PATH.write_text(json.dumps(document, indent=2) + "\n", encoding="utf-8")
    MD_PATH.write_text(_markdown(document) + "\n", encoding="utf-8")

    drift = document["paired_drift"]
    seeds = document["seed_sweep"]
    topology = document["topology_sweep"]
    cap = document["cap_ablation"]
    paired = document["correlation_paired_test"]

    checks = {
        "paired_drift_has_16_and_4": (
            drift["design"]["drifted_personas"] == 16
            and drift["design"]["stable_personas"] == 4
        ),
        "seed_filtered_precision_all_one": seeds["invariants"][
            "filtered_precision_all_one"
        ],
        "seed_filtered_false_merge_all_zero": seeds["invariants"][
            "filtered_false_merge_all_zero"
        ],
        "seed_careful_recall_all_one": seeds["invariants"][
            "careful_recall_all_one"
        ],
        "seed_careful_fp_all_zero": seeds["invariants"]["careful_fp_all_zero"],
        "all_topologies_filtered_perfect": all(
            entry["invariants"]["filtered_precision_all_one"]
            and entry["invariants"]["filtered_false_merge_all_zero"]
            for entry in topology["by_topology"].values()
        ),
        "derived_cap_is_perfect": any(
            row["derived_cap"] and row["precision"] == 1.0 and row["recall"] == 1.0
            for row in cap["rows"]
        ),
        "below_cluster_cap_loses_recall": any(
            row["cap"] is not None
            and row["cap"] < cap["design"]["services_per_cluster"]
            and row["recall"] < 1.0
            for row in cap["rows"]
        ),
        "paired_test_has_12_queries": paired["design"]["queries"] == 12,
    }

    print(f"wrote {JSON_PATH.relative_to(ROOT)}")
    print(f"wrote {MD_PATH.relative_to(ROOT)}")
    print()
    print(_markdown(document))
    failed = [name for name, ok in checks.items() if not ok]
    if failed:
        print(f"VERDICT: {len(checks) - len(failed)} of {len(checks)} checks passed; "
              f"failed: {', '.join(failed)}")
        return 1
    print(f"VERDICT: {len(checks)} design and invariant checks passed")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
